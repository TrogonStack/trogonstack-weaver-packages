import inspect

from opentelemetry.sdk.metrics import MeterProvider
from opentelemetry.sdk.metrics.export import (
    HistogramDataPoint,
    InMemoryMetricReader,
    Metric,
    NumberDataPoint,
)
from opentelemetry.util.types import AttributeValue

import semconv
from semconv import (
    INSTRUMENTATION_NAME,
    INSTRUMENTATION_VERSION,
    SCHEMA_URL,
    attributes,
    metrics,
)


def collect(reader: InMemoryMetricReader) -> dict[str, Metric]:
    data = reader.get_metrics_data()
    assert data is not None
    scopes = data.resource_metrics[0].scope_metrics
    assert len(scopes) == 1
    scope = scopes[0].scope
    assert scope.name == INSTRUMENTATION_NAME
    assert scope.version == INSTRUMENTATION_VERSION
    assert scope.schema_url == SCHEMA_URL
    return {metric.name: metric for metric in scopes[0].metrics}


def new_provider() -> tuple[InMemoryMetricReader, MeterProvider]:
    reader = InMemoryMetricReader()
    return reader, MeterProvider(metric_readers=[reader])


def attributes_of(
    point: NumberDataPoint | HistogramDataPoint,
) -> dict[str, AttributeValue]:
    return dict(point.attributes or {})


def number_points(metric: Metric) -> list[NumberDataPoint]:
    points = list(metric.data.data_points)
    assert all(isinstance(point, NumberDataPoint) for point in points)
    return [point for point in points if isinstance(point, NumberDataPoint)]


def histogram_points(metric: Metric) -> list[HistogramDataPoint]:
    points = list(metric.data.data_points)
    assert all(isinstance(point, HistogramDataPoint) for point in points)
    return [point for point in points if isinstance(point, HistogramDataPoint)]


def test_instrumentation_identity_comes_from_the_params() -> None:
    assert INSTRUMENTATION_NAME == "acme-billing"
    assert INSTRUMENTATION_VERSION == "1.2.3"
    assert SCHEMA_URL == "https://example.com/schemas/params/1.0.0"


def test_the_meter_carries_the_configured_identity() -> None:
    reader, provider = new_provider()
    metrics.BillingInvoiceCreated(metrics.get_meter(provider)).add(
        1, invoice_id="inv-1"
    )
    data = reader.get_metrics_data()
    assert data is not None
    scope = data.resource_metrics[0].scope_metrics[0].scope
    assert (scope.name, scope.version) == ("acme-billing", "1.2.3")
    assert scope.schema_url == SCHEMA_URL
    collect(reader)


def test_the_module_docstring_comes_from_the_params() -> None:
    assert semconv.__doc__ == "Typed instruments for the synthetic billing registry."


def test_every_module_carries_the_configured_header() -> None:
    header = (
        "# Code generated by weaver from the synthetic billing registry."
        " DO NOT EDIT.\n"
        "# Run `mise run semconv:generate` after changing a convention.\n"
    )
    for module in (semconv, attributes, metrics):
        source = inspect.getsource(module)
        assert source.startswith(header)


def test_the_vendor_prefix_is_dropped_from_names() -> None:
    assert attributes.BILLING_INVOICE_ID_KEY == "acme.billing.invoice.id"
    assert attributes.BILLING_INVOICE_PAID_KEY == "billing.invoice.paid"
    assert attributes.BillingInvoiceCurrency.EUR.value == "EUR"
    assert metrics.BillingInvoiceCreated.NAME == "acme.billing.invoice.created"
    assert not hasattr(attributes, "ACME_BILLING_INVOICE_ID_KEY")
    assert not hasattr(metrics, "AcmeBillingInvoiceCreated")


def test_parameters_drop_the_vendor_prefix_and_the_namespace() -> None:
    parameters = inspect.signature(metrics.BillingInvoiceCreated.add).parameters
    assert list(parameters) == [
        "self",
        "amount",
        "invoice_id",
        "invoice_currency",
        "invoice_paid",
        "context",
    ]


def test_attributes_keep_their_registry_keys_when_recorded() -> None:
    reader, provider = new_provider()
    metrics.BillingInvoiceCreated(metrics.get_meter(provider)).add(
        3,
        invoice_id="inv-1",
        invoice_currency=attributes.BillingInvoiceCurrency.USD,
        invoice_paid=True,
    )
    (point,) = number_points(collect(reader)["acme.billing.invoice.created"])
    assert point.value == 3
    assert attributes_of(point) == {
        "acme.billing.invoice.id": "inv-1",
        "acme.billing.invoice.currency": "USD",
        "billing.invoice.paid": True,
    }
