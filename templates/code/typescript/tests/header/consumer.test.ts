import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { createRecorder } from "../../support.ts";
import * as Metrics from "./metrics.ts";
import { SCHEMA_URL } from "./schema.ts";

test("the scope carries the configured name, version and schema URL", async () => {
  const recorder = createRecorder();
  new Metrics.MyappTaskStarted(Metrics.getMeter(recorder.meterProvider)).add(1, {
    taskId: "task_0001",
  });
  await recorder.metric("myapp.task.started");
  const [scope] = await recorder.scopes();
  assert.deepEqual(
    [scope?.scope.name, scope?.scope.version, scope?.scope.schemaUrl],
    ["myapp-metrics", "1.2.3", SCHEMA_URL],
  );
  assert.equal(Metrics.INSTRUMENTATION_NAME, "myapp-metrics");
  assert.equal(Metrics.INSTRUMENTATION_VERSION, "1.2.3");
});

test("the header names the source and the regenerate command", () => {
  const header = readFileSync(new URL("./metrics.ts", import.meta.url), "utf8").split("\n", 3);
  assert.deepEqual(header, [
    "// Generated by OpenTelemetry Weaver. Do not edit.",
    "// Source: myapp semantic conventions 1.0.0",
    "// Regenerate: mise run semconv:generate",
  ]);
});
